		JOIN DBAMV.CONVENIO        C    
		ON C.CD_CONVENIO     = A.CD_CONVENIO
		
		--LEFT JOIN DBAMV.ESPECIALID E    
		--ON E.CD_ESPECIALID   = A.CD_ESPECIALID
		
		JOIN PARAMS                P    
		ON A.CD_MULTI_EMPRESA = P.CD_EMPRESA
		
		JOIN CONTADOR              CT   
		ON TRUNC(MI.DT_MOV_INT) = CT.DATA
		
		LEFT JOIN PACIENTE PA
		ON A.CD_PACIENTE = PA.CD_PACIENTE
    
	WHERE 
		MI.TP_MOV          = 'I'
		AND A.TP_ATENDIMENTO   IN ('I', 'H', 'U')
		AND A.DT_ALTA          IS NOT NULL
		AND TRUNC(A.DT_ATENDIMENTO) = TRUNC(A.DT_ALTA)
		AND PA.NM_PACIENTE NOT LIKE '%TESTE%'
		AND NOT EXISTS 
		(
		SELECT
			'X' 
		FROM 
			DBAMV.MOV_INT MI2
		
		WHERE 
			MI2.CD_ATENDIMENTO = MI.CD_ATENDIMENTO
			AND TO_DATE(TO_CHAR(MI2.DT_MOV_INT,'DD/MM/YYYY') || TO_CHAR(MI2.HR_MOV_INT,'HH24:MISS'), 'DD/MM/YYYYHH24:MISS')
			< TO_DATE(TO_CHAR(MI.DT_MOV_INT,'DD/MM/YYYY')  || TO_CHAR(MI.HR_MOV_INT,'HH24:MISS'),  'DD/MM/YYYYHH24:MISS')
			AND MI2.CD_LEITO       = MI.CD_LEITO
			AND MI2.CD_TIP_ACOM   <> MI.CD_TIP_ACOM
			AND NVL(MI2.CD_LEITO_ANTERIOR, MI2.CD_LEITO) = NVL(MI.CD_LEITO_ANTERIOR, MI.CD_LEITO)
		)
		
    GROUP BY
		A.CD_MULTI_EMPRESA,
		CT.DATA,
        UI.CD_UNID_INT,
		A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO

    UNION

    -- OBITOS DO DIA (ENTRADA E SAIDA POR OBITO NO MESMO DIA)
    SELECT
		A.CD_MULTI_EMPRESA,
		CT.DATA AS DT_REFERENCIA,
		UI.CD_UNID_INT,
        A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO,
        0 AS PAC_INT_00H,   
		0 AS ENT_INTERNADOS, 
		0 AS ENT_TRANSF,
        0 AS SAI_ALTAS,     
		0 AS SAI_TRANSFPARA, 
		0 AS SAI_OBITOS,
        0 AS SAI_OBITOS48,  
		0 AS SAI_OBITOS24,   
		0 AS HOSP_DIA,
        COUNT(*) AS OBITO_DIA
		
    FROM 
		DBAMV.ATENDIME        A
		JOIN DBAMV.LEITO           L    
		ON L.CD_LEITO      = A.CD_LEITO
		
		JOIN DBAMV.UNID_INT        UI   
		ON UI.CD_UNID_INT  = L.CD_UNID_INT
		
		JOIN DBAMV.MOT_ALT         MA   
		ON MA.CD_MOT_ALT   = A.CD_MOT_ALT
		
		JOIN DBAMV.CONVENIO        C   
		ON C.CD_CONVENIO   = A.CD_CONVENIO
		
		--LEFT JOIN DBAMV.ESPECIALID E    
		--ON E.CD_ESPECIALID = A.CD_ESPECIALID
		
		JOIN PARAMS                P    
		ON A.CD_MULTI_EMPRESA = P.CD_EMPRESA
		
		JOIN CONTADOR              CT   
		ON TRUNC(A.DT_ATENDIMENTO) = TRUNC(CT.DATA)
		
		LEFT JOIN PACIENTE PA
		ON A.CD_PACIENTE = PA.CD_PACIENTE
   
   WHERE 
		MA.TP_MOT_ALTA     = 'O'
		AND A.TP_ATENDIMENTO   IN ('I', 'U')
		AND TRUNC(A.DT_ATENDIMENTO) = TRUNC(A.DT_ALTA)
        AND PA.NM_PACIENTE NOT LIKE '%TESTE%'
	
	GROUP BY
		A.CD_MULTI_EMPRESA,
		CT.DATA,
		UI.CD_UNID_INT,
		A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO

)

GROUP BY
	CD_MULTI_EMPRESA,
	DT_REFERENCIA,
    CD_UNID_INT,
    CD_ESPECIALID,
	CD_ORI_ATE,
	TP_ATENDIMENTO
	
ORDER BY 
	DT_REFERENCIA