		A.CD_MULTI_EMPRESA,
		CT.DATA AS DT_REFERENCIA,
		UI.CD_UNID_INT,
        A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO,
        0 AS PAC_INT_00H,   
		0 AS ENT_INTERNADOS, 
		0 AS ENT_TRANSF,
        0 AS SAI_ALTAS,     
		COUNT(*) AS SAI_TRANSFPARA,
        0 AS SAI_OBITOS,    
		0 AS SAI_OBITOS48,   
		0 AS SAI_OBITOS24,
        0 AS HOSP_DIA,      
		0 AS OBITO_DIA
		
    FROM 
		DBAMV.MOV_INT        MI
		JOIN DBAMV.ATENDIME        A    
		ON A.CD_ATENDIMENTO   = MI.CD_ATENDIMENTO
		
		JOIN DBAMV.LEITO           L    
		ON L.CD_LEITO         = MI.CD_LEITO_ANTERIOR
		
		JOIN DBAMV.LEITO           L1   
		ON L1.CD_LEITO        = MI.CD_LEITO
		
		JOIN DBAMV.UNID_INT        UI   
		ON UI.CD_UNID_INT     = L.CD_UNID_INT
		
		JOIN DBAMV.UNID_INT        UI1  
		ON UI1.CD_UNID_INT    = L1.CD_UNID_INT
		
		JOIN DBAMV.CONVENIO        C    
		ON C.CD_CONVENIO      = A.CD_CONVENIO
		
		--LEFT JOIN DBAMV.ESPECIALID E    
		--ON E.CD_ESPECIALID    = A.CD_ESPECIALID
		
		JOIN PARAMS                P    
		ON A.CD_MULTI_EMPRESA = P.CD_EMPRESA
		
		JOIN CONTADOR              CT   
		ON TRUNC(MI.DT_MOV_INT) = CT.DATA
		
		LEFT JOIN PACIENTE PA
		ON A.CD_PACIENTE = PA.CD_PACIENTE
    
	WHERE 
		MI.TP_MOV          = 'O'
		AND UI.CD_UNID_INT    <> UI1.CD_UNID_INT
		AND A.TP_ATENDIMENTO   IN ('I', 'H', 'U')
		AND PA.NM_PACIENTE NOT LIKE '%TESTE%'
		AND NOT EXISTS
		(
		SELECT 
		'X' 
		
		FROM 
		DBAMV.MOV_INT MI2
		
		WHERE 
		MI2.CD_ATENDIMENTO = MI.CD_ATENDIMENTO
		AND TO_DATE(TO_CHAR(MI2.DT_MOV_INT,'DD/MM/YYYY') || TO_CHAR(MI2.HR_MOV_INT,'HH24:MISS'), 'DD/MM/YYYYHH24:MISS')
		< TO_DATE(TO_CHAR(MI.DT_MOV_INT,'DD/MM/YYYY')  || TO_CHAR(MI.HR_MOV_INT,'HH24:MISS'),  'DD/MM/YYYYHH24:MISS')
		AND MI2.CD_LEITO       = MI.CD_LEITO
		AND MI2.CD_TIP_ACOM   <> MI.CD_TIP_ACOM
		AND NVL(MI2.CD_LEITO_ANTERIOR, MI2.CD_LEITO) = NVL(MI.CD_LEITO_ANTERIOR, MI.CD_LEITO)
		
		)
    GROUP BY
		A.CD_MULTI_EMPRESA,
		CT.DATA,
        UI.CD_UNID_INT,
		A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO

    UNION

    -- SAIDAS DE PACIENTES COM OBITOS NO PERIODO
    SELECT
		A.CD_MULTI_EMPRESA,
		CT.DATA AS DT_REFERENCIA,
		UI.CD_UNID_INT,
        A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO,
        0 AS PAC_INT_00H,   
		0 AS ENT_INTERNADOS, 
		0 AS ENT_TRANSF,
        0 AS SAI_ALTAS,     
		0 AS SAI_TRANSFPARA,
        COUNT(*) AS SAI_OBITOS,
        0 AS SAI_OBITOS48,  
		0 AS SAI_OBITOS24,
        0 AS HOSP_DIA,      
		0 AS OBITO_DIA
		
    FROM 
		DBAMV.ATENDIME        A
		JOIN DBAMV.LEITO           L    
		ON L.CD_LEITO      = A.CD_LEITO
		
		JOIN DBAMV.UNID_INT        UI   
		ON UI.CD_UNID_INT  = L.CD_UNID_INT
		
		JOIN DBAMV.MOT_ALT         MA   
		ON MA.CD_MOT_ALT   = A.CD_MOT_ALT
		
		LEFT JOIN DBAMV.CONVENIO   C    
		ON C.CD_CONVENIO   = A.CD_CONVENIO
		
		--LEFT JOIN DBAMV.ESPECIALID E    
		--ON E.CD_ESPECIALID = A.CD_ESPECIALID
		
		JOIN PARAMS                P    
		ON A.CD_MULTI_EMPRESA = P.CD_EMPRESA
		
		JOIN CONTADOR              CT   
		ON TRUNC(A.DT_ALTA) = CT.DATA
		
		LEFT JOIN PACIENTE PA
		ON A.CD_PACIENTE = PA.CD_PACIENTE
    
	WHERE 
		MA.TP_MOT_ALTA     = 'O'
		AND A.TP_ATENDIMENTO   IN ('I', 'U')
		AND PA.NM_PACIENTE NOT LIKE '%TESTE%'
		
	GROUP BY
		A.CD_MULTI_EMPRESA,
		CT.DATA,
        UI.CD_UNID_INT,
		A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO

    UNION

    -- SAIDAS DE PACIENTES COM OBITOS COM MAIS DE 24 HORAS NO PERIODO
    SELECT
		A.CD_MULTI_EMPRESA,
		CT.DATA AS DT_REFERENCIA,
		UI.CD_UNID_INT,
        A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO,
        0 AS PAC_INT_00H,   
		0 AS ENT_INTERNADOS, 
		0 AS ENT_TRANSF,
        0 AS SAI_ALTAS,     
		0 AS SAI_TRANSFPARA, 
		0 AS SAI_OBITOS,
        COUNT(*) AS SAI_OBITOS48,
        0 AS SAI_OBITOS24,  
		0 AS HOSP_DIA,       
		0 AS OBITO_DIA
		
    FROM 
		DBAMV.ATENDIME        A
		JOIN DBAMV.LEITO           L    
		ON L.CD_LEITO      = A.CD_LEITO
		
		JOIN DBAMV.UNID_INT        UI   
		ON UI.CD_UNID_INT  = L.CD_UNID_INT
		
		JOIN DBAMV.MOT_ALT         MA   
		ON MA.CD_MOT_ALT   = A.CD_MOT_ALT
		
		JOIN DBAMV.CONVENIO        C    
		ON C.CD_CONVENIO   = A.CD_CONVENIO
		
		--LEFT JOIN DBAMV.ESPECIALID E    
		--ON E.CD_ESPECIALID = A.CD_ESPECIALID
		
		JOIN PARAMS                P    
		ON A.CD_MULTI_EMPRESA = P.CD_EMPRESA
		
		JOIN CONTADOR              CT   
		ON TRUNC(A.DT_ALTA) = CT.DATA
		
		LEFT JOIN PACIENTE PA
		ON A.CD_PACIENTE = PA.CD_PACIENTE
    
	WHERE 
		MA.TP_MOT_ALTA     = 'O'
		 AND A.TP_ATENDIMENTO   IN ('I', 'U')
		 AND DBAMV.FNC_MV_RECUPERA_DATA_HORA(A.DT_ALTA, A.HR_ALTA)
		- DBAMV.FNC_MV_RECUPERA_DATA_HORA(A.DT_ATENDIMENTO, A.HR_ATENDIMENTO) > 1
