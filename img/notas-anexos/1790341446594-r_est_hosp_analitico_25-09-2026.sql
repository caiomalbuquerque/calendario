    -- HOSPITAL DIA (ENTRADA E SAIDA NO MESMO DIA)
    SELECT
		A.CD_MULTI_EMPRESA,
		CT.DATA AS DT_REFERENCIA,
		UI.CD_UNID_INT,
        A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO,
        0 AS PAC_INT_00H,   
		0 AS ENT_INTERNADOS, 
		0 AS ENT_TRANSF,
        0 AS SAI_ALTAS,     
		0 AS SAI_TRANSFPARA, 
		0 AS SAI_OBITOS,
        0 AS SAI_OBITOS48,  
		0 AS SAI_OBITOS24,
        COUNT(*) AS HOSP_DIA,
        0 AS OBITO_DIA
		
    FROM 
		DBAMV.MOV_INT        MI
