		  (
			  SELECT 
				'X' 
			  
			  FROM 
				DBAMV.MOV_INT MI2
			  
			  WHERE 
				MI2.CD_ATENDIMENTO = MI.CD_ATENDIMENTO
				AND TO_DATE(TO_CHAR(MI2.DT_MOV_INT,'DD/MM/YYYY') || TO_CHAR(MI2.HR_MOV_INT,'HH24:MISS'), 'DD/MM/YYYYHH24:MISS')
				< TO_DATE(TO_CHAR(MI.DT_MOV_INT,'DD/MM/YYYY')  || TO_CHAR(MI.HR_MOV_INT,'HH24:MISS'),  'DD/MM/YYYYHH24:MISS')
				AND MI2.CD_LEITO       = MI.CD_LEITO
				AND MI2.CD_TIP_ACOM   <> MI.CD_TIP_ACOM
				AND NVL(MI2.CD_LEITO_ANTERIOR, MI2.CD_LEITO) = NVL(MI.CD_LEITO_ANTERIOR, MI.CD_LEITO)
		  )
	  
    GROUP BY
		A.CD_MULTI_EMPRESA,
		CT.DATA,
        UI.CD_UNID_INT,
		A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO

