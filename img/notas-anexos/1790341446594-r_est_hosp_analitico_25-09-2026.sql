		A.CD_MULTI_EMPRESA,
		CT.DATA AS DT_REFERENCIA,
		UI.CD_UNID_INT,
        A.CD_ESPECIALID,
		A.CD_ORI_ATE,
		A.TP_ATENDIMENTO,
        0 AS PAC_INT_00H,   
		0 AS ENT_INTERNADOS,
        COUNT(*) AS ENT_TRANSF,
        0 AS SAI_ALTAS,     
		0 AS SAI_TRANSFPARA, 
		0 AS SAI_OBITOS,
        0 AS SAI_OBITOS48,  
		0 AS SAI_OBITOS24,   
		0 AS HOSP_DIA,
        0 AS OBITO_DIA
		
    FROM DBAMV.MOV_INT        MI
		JOIN DBAMV.ATENDIME        A   
		ON A.CD_ATENDIMENTO   = MI.CD_ATENDIMENTO
		
		JOIN DBAMV.LEITO           L    
		ON L.CD_LEITO         = MI.CD_LEITO
		
		JOIN DBAMV.LEITO           L1   
		ON L1.CD_LEITO        = MI.CD_LEITO_ANTERIOR
		
		JOIN DBAMV.UNID_INT        UI   
		ON UI.CD_UNID_INT     = L.CD_UNID_INT
		
		JOIN DBAMV.UNID_INT        UI1  
		ON UI1.CD_UNID_INT    = L1.CD_UNID_INT
		
		JOIN DBAMV.CONVENIO        C    
		ON C.CD_CONVENIO      = A.CD_CONVENIO
		
