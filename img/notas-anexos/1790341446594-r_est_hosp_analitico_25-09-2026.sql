        0 AS SAI_TRANSFPARA, 
		0 AS SAI_OBITOS,    
		0 AS SAI_OBITOS48,
        0 AS SAI_OBITOS24,   
		0 AS HOSP_DIA,       
		0 AS OBITO_DIA
		
    FROM 
		DBAMV.ATENDIME        A
		JOIN DBAMV.LEITO           L    
		ON L.CD_LEITO      = A.CD_LEITO
		
		JOIN DBAMV.UNID_INT        UI   
		ON UI.CD_UNID_INT  = L.CD_UNID_INT
		
